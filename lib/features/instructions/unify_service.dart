/// "Unificar instruções" (SPEC-113 R3, R4): compares the `CLAUDE.md` and the
/// `AGENTS.md` by section (Markdown headings) and item (list lines and
/// paragraphs), lets each difference go to the `AGENTS.md`, stay in the
/// `CLAUDE.md` as a Claude-only part or be picked between the two versions,
/// and composes both files before anything is written.

// --- Quando oferecer (R3) -------------------------------------------------------

/// Whether "Unificar instruções" is offered for these texts (R3): a
/// `CLAUDE.md` alone, two sources (an `AGENTS.md` of the person's not
/// imported), or an `AGENTS.md` generated by the app. Never for the single
/// source (already unified) nor for a project without `CLAUDE.md`.
bool canUnifyTexts({String? claude, String? agents}) {
  if (claude == null) return false;
  return switch (agentsMdState(claude: claude, agents: agents)) {
    AgentsMdState.absent ||
    AgentsMdState.personal ||
    AgentsMdState.fresh ||
    AgentsMdState.stale => true,
    AgentsMdState.singleSource => false,
  };
}

/// [canUnifyTexts] of an inventory: what the Instruções tab asks (R3).
bool canUnify(InstructionsInventory inv) =>
    canUnifyTexts(claude: inv.claudeText, agents: inv.agentsText);

// --- Markdown em seções e itens -------------------------------------------------

/// One item of a section: a top-level list line (with its indented
/// continuation), a paragraph, a table or a fenced code block.
@immutable
class MdItem {
  const MdItem(this.text, {this.isList = false});

  final String text;
  final bool isList;

  /// The item compared: blanks collapsed.
  String get key => _collapse(text);
}

/// One section: a heading (null = the text before the first heading) and
/// its items.
@immutable
class MdSection {
  const MdSection({this.heading, this.level = 0, required this.items});

  /// The heading line as written (`## Comandos`).
  final String? heading;
  final int level;
  final List<MdItem> items;

  /// The heading text (`Comandos`); empty for the preamble.
  String get title => heading == null ? '' : _headingTitle(heading!);

  /// Sections are matched by title, ignoring case and blanks.
  String get key => heading == null ? '\u0000' : _collapse(title).toLowerCase();
}

String _collapse(String s) => s.trim().replaceAll(RegExp(r'\s+'), ' ');

final _headingRe = RegExp(r'^ {0,3}(#{1,6})\s+(.*?)\s*#*\s*$');
final _listRe = RegExp(r'^([-*+]|\d+[.)])\s+');
final _fenceRe = RegExp(r'^ {0,3}(`{3,}|~{3,})');

String _headingTitle(String heading) =>
    _headingRe.firstMatch(heading)?.group(2) ?? heading.trim();

/// [text] split into sections and items. Blank lines only separate items;
/// [renderMdSections] writes them back in a normalized layout.
List<MdSection> parseMdSections(String text) {
  final sections = <MdSection>[];
  String? heading;
  var level = 0;
  var items = <MdItem>[];
  List<String>? current;
  var currentList = false;
  String? fence;

  void endItem() {
    if (current != null) {
      items.add(MdItem(current!.join('\n'), isList: currentList));
    }
    current = null;
    currentList = false;
  }

  void endSection() {
    endItem();
    if (heading != null || items.isNotEmpty) {
      sections.add(MdSection(heading: heading, level: level, items: items));
    }
    items = <MdItem>[];
  }

  for (final raw in text.replaceAll('\r\n', '\n').split('\n')) {
    final line = raw.trimRight();
    if (fence != null) {
      current!.add(line);
      final m = _fenceRe.firstMatch(line);
      if (m != null &&
          m.group(1)![0] == fence[0] &&
          m.group(1)!.length >= fence.length &&
          line.trim() == m.group(1)) {
        fence = null;
        endItem();
      }
      continue;
    }
    final f = _fenceRe.firstMatch(line);
    if (f != null) {
      // A fence indented under a list item belongs to it.
      if (current != null && currentList && raw.startsWith(' ')) {
        current!.add(line);
        fence = f.group(1);
        continue;
      }
      endItem();
      current = [line];
      fence = f.group(1);
      continue;
    }
    final h = _headingRe.firstMatch(line);
    if (h != null) {
      endSection();
      heading = line.trim();
      level = h.group(1)!.length;
      continue;
    }
    if (line.trim().isEmpty) {
      endItem();
      continue;
    }
    if (_listRe.hasMatch(line)) {
      endItem();
      current = [line];
      currentList = true;
      continue;
    }
    if (current != null) {
      current!.add(line);
      continue;
    }
    current = [line];
  }
  endSection();
  return sections;
}

/// [sections] as Markdown: heading, items right under it (consecutive list
/// items without a blank line between them, others with one), a blank line between sections
/// and a newline at the end; empty when there is nothing.
String renderMdSections(List<MdSection> sections) {
  final parts = <String>[];
  for (final s in sections) {
    final b = StringBuffer();
    if (s.heading != null) b.write(s.heading);
    for (var i = 0; i < s.items.length; i++) {
      final item = s.items[i];
      if (b.isNotEmpty) {
        final prev = i == 0 ? null : s.items[i - 1];
        b.write(prev == null || (prev.isList && item.isList) ? '\n' : '\n\n');
      }
      b.write(item.text);
    }
    if (b.isNotEmpty) parts.add(b.toString());
  }
  return parts.isEmpty ? '' : '${parts.join('\n\n')}\n';
}

// --- Diferenças (R4) ------------------------------------------------------------

/// What a difference is.
enum UnifyDiffKind {
  /// The same item, written differently in each file.
  changed,

  /// Only in the `CLAUDE.md` (an item or a whole section).
  onlyClaude,

  /// Only in the `AGENTS.md` (an item or a whole section).
  onlyAgents,
}

/// Where a difference ends up (R4).
enum UnifyTarget {
  /// Goes to the `AGENTS.md` (one-sided differences).
  agents,

  /// Stays in the `CLAUDE.md`, as a part only the Claude Code reads.
  claudeOnly,

  /// The `CLAUDE.md` version goes to the `AGENTS.md` ([UnifyDiffKind.changed]).
  claudeVersion,

  /// The `AGENTS.md` version stays ([UnifyDiffKind.changed]).
  agentsVersion,

  /// Another text, written in the dialog ([UnifyDiffKind.changed]).
  custom,
}

/// One difference between the two files (R4).
@immutable
class UnifyDiff {
  const UnifyDiff({
    required this.id,
    required this.kind,
    required this.section,
    required this.title,
    this.claudeText,
    this.agentsText,
    this.wholeSection = false,
    this.claudeSpecific = false,
  });

  /// `d1`, `d2`… (the AI answers by it).
  final String id;
  final UnifyDiffKind kind;

  /// Title of the section it is in (empty = before any heading).
  final String section;

  /// Short name for the list.
  final String title;
  final String? claudeText;
  final String? agentsText;

  /// A section that exists only in one file, compared as one block.
  final bool wholeSection;

  /// Mentions what only the Claude Code has (subagents, `.claude/`…): by
  /// default it stays in the `CLAUDE.md`.
  final bool claudeSpecific;

  /// The destinations this difference accepts.
  List<UnifyTarget> get targets => kind == UnifyDiffKind.changed
      ? const [
          UnifyTarget.claudeVersion,
          UnifyTarget.agentsVersion,
          UnifyTarget.custom,
        ]
      : const [UnifyTarget.agents, UnifyTarget.claudeOnly];

  /// The destination before the person (or the AI) says otherwise: the
  /// `CLAUDE.md` version (it was the source, SPEC-104), the `AGENTS.md` for
  /// common text, the `CLAUDE.md` for what only the Claude Code has.
  UnifyTarget get defaultTarget => switch (kind) {
    UnifyDiffKind.changed => UnifyTarget.claudeVersion,
    UnifyDiffKind.onlyClaude =>
      claudeSpecific ? UnifyTarget.claudeOnly : UnifyTarget.agents,
    UnifyDiffKind.onlyAgents => UnifyTarget.agents,
  };
}

/// One piece of an aligned section: common text or a difference.
@immutable
class _Entry {
  const _Entry.common(MdItem this.item) : diff = null;
  const _Entry.diff(UnifyDiff this.diff) : item = null;

  final MdItem? item;
  final UnifyDiff? diff;
}

/// One section of the result, in order: a section of both files (or only
/// one, without items), or a whole-section difference.
@immutable
class _Block {
  const _Block({
    this.heading,
    this.level = 0,
    this.entries = const [],
    this.sectionDiff,
    this.section,
  });

  final String? heading;
  final int level;
  final List<_Entry> entries;
  final UnifyDiff? sectionDiff;

  /// The section of a [sectionDiff].
  final MdSection? section;
}

/// The comparison of the two files (R4): the differences and how to put the
/// result together.
@immutable
class UnifyPlan {
  const UnifyPlan._(
    this._blocks, {
    required this.diffs,
    required this.agentsGenerated,
    required this.hadAgents,
  });

  /// The differences, in file order.
  final List<UnifyDiff> diffs;
  final List<_Block> _blocks;

  /// The `AGENTS.md` was generated by the app: treated as a copy, its text
  /// is not a source of the person's (R3, R4).
  final bool agentsGenerated;

  /// There was an `AGENTS.md` of the person's to compare with.
  final bool hadAgents;

  Map<String, UnifyTarget> get defaults => {
    for (final d in diffs) d.id: d.defaultTarget,
  };

  UnifyDiff? diff(String id) {
    for (final d in diffs) {
      if (d.id == id) return d;
    }
    return null;
  }
}

/// The two files after the unification (R4), before writing.
@immutable
class UnifyResult {
  const UnifyResult({
    required this.agents,
    required this.claude,
    required this.claudeOnly,
  });

  /// The full `AGENTS.md`.
  final String agents;

  /// The `CLAUDE.md`: `@AGENTS.md` and the Claude-only part.
  final String claude;

  /// The Claude-only part alone (empty = only the import).
  final String claudeOnly;
}

final _claudeSpecificRe = RegExp(
  r'claude code|subagente|subagent|\.claude/|slash command|comando /|'
  r'hooks? do claude|claude\.md',
  caseSensitive: false,
);

final _wordRe = RegExp(r'[\p{L}\p{N}_]+', unicode: true);

/// List marker, emphasis and code marks out: what the person reads.
String _plain(String s) => s
    .replaceFirst(_listRe, '')
    .replaceAll(RegExp(r'[`*_]'), '')
    .replaceAll(RegExp(r'^#+\s*'), '')
    .trim();

/// The label before `:` of an item (`Testes` of `- Testes: …`), if short.
String? _label(String item) {
  final first = _plain(item.split('\n').first);
  final i = first.indexOf(':');
  if (i < 2 || i > 40) return null;
  return first.substring(0, i).trim();
}

String _itemTitle(String item) {
  final label = _label(item);
  if (label != null) return label;
  final first = _plain(item.split('\n').first);
  return first.length <= 48 ? first : '${first.substring(0, 47).trimRight()}…';
}

Set<String> _words(String s) => {
  for (final m in _wordRe.allMatches(s.toLowerCase())) m.group(0)!,
};

/// How alike two items are (0–1): the same label counts as the same item.
double _similarity(String a, String b) {
  final la = _label(a)?.toLowerCase(), lb = _label(b)?.toLowerCase();
  if (la != null && la == lb) return 1;
  final wa = _words(a), wb = _words(b);
  if (wa.isEmpty || wb.isEmpty) return 0;
  final inter = wa.intersection(wb).length;
  return inter / (wa.length + wb.length - inter);
}

/// Pairs of indexes (i in [a], j in [b]) of the longest common subsequence
/// of keys.
List<(int, int)> _lcs<T>(List<T> a, List<T> b, String Function(T) key) {
  final n = a.length, m = b.length;
  final ka = [for (final x in a) key(x)], kb = [for (final x in b) key(x)];
  final t = List.generate(n + 1, (_) => List<int>.filled(m + 1, 0));
  for (var i = n - 1; i >= 0; i--) {
    for (var j = m - 1; j >= 0; j--) {
      t[i][j] = ka[i] == kb[j]
          ? t[i + 1][j + 1] + 1
          : (t[i + 1][j] >= t[i][j + 1] ? t[i + 1][j] : t[i][j + 1]);
    }
  }
  final out = <(int, int)>[];
  var i = 0, j = 0;
  while (i < n && j < m) {
    if (ka[i] == kb[j]) {
      out.add((i++, j++));
    } else if (t[i + 1][j] >= t[i][j + 1]) {
      i++;
    } else {
      j++;
    }
  }
  return out;
}

/// Aligned walk of [a] and [b] by [pairs]: (ia, ib) with one side null
/// where only one list has the element, in the order of both.
List<(int?, int?)> _align(int a, int b, List<(int, int)> pairs) {
  final out = <(int?, int?)>[];
  var i = 0, j = 0;
  for (final (pi, pj) in [...pairs, (a, b)]) {
    while (i < pi) {
      out.add((i++, null));
    }
    while (j < pj) {
      out.add((null, j++));
    }
    if (pi < a && pj < b) out.add((i++, j++));
  }
  return out;
}

/// Compares [claude] and [agents] (R4). The import line of the `CLAUDE.md`
/// is left out; an `AGENTS.md` generated by the app (with the marker) is
/// treated as a copy, as if absent (R3).
UnifyPlan buildUnifyPlan({required String? claude, required String? agents}) {
  final generated = agents != null && agentsMdMarker(agents) != null;
  final personal = generated ? null : agents;
  final cs = parseMdSections(
    claude == null ? '' : splitClaudeMd(claude).claudeOnly,
  );
  final as = parseMdSections(personal ?? '');
  final diffs = <UnifyDiff>[];
  final blocks = <_Block>[];
  var next = 1;
  UnifyDiff add(UnifyDiff Function(String id) make) {
    final d = make('d${next++}');
    diffs.add(d);
    return d;
  }

  final sectionPairs = _lcs(cs, as, (s) => s.key);
  for (final (ci, ai) in _align(cs.length, as.length, sectionPairs)) {
    if (ci != null && ai != null) {
      blocks.add(_sharedBlock(cs[ci], as[ai], add));
      continue;
    }
    final s = ci != null ? cs[ci] : as[ai!];
    if (s.items.isEmpty) {
      // A heading alone (the `# título` over the sections) is structure.
      blocks.add(_Block(heading: s.heading, level: s.level));
      continue;
    }
    final fromClaude = ci != null;
    final text = renderMdSections([s]).trimRight();
    final d = add(
      (id) => UnifyDiff(
        id: id,
        kind: fromClaude ? UnifyDiffKind.onlyClaude : UnifyDiffKind.onlyAgents,
        section: s.title,
        title: s.heading == null ? 'Início do arquivo' : _plain(s.title),
        claudeText: fromClaude ? text : null,
        agentsText: fromClaude ? null : text,
        wholeSection: true,
        claudeSpecific: fromClaude && _claudeSpecificRe.hasMatch(text),
      ),
    );
    blocks.add(_Block(sectionDiff: d, section: s));
  }
  return UnifyPlan._(
    blocks,
    diffs: diffs,
    agentsGenerated: generated,
    hadAgents: personal != null,
  );
}

_Block _sharedBlock(
  MdSection c,
  MdSection a,
  UnifyDiff Function(UnifyDiff Function(String id)) add,
) {
  final aligned = _align(
    c.items.length,
    a.items.length,
    _lcs(c.items, a.items, (i) => i.key),
  );
  // Items of one side only: pair the alike ones as "changed" (best first).
  final onlyC = [
    for (final (ci, ai) in aligned)
      if (ai == null) ci!,
  ];
  final onlyA = [
    for (final (ci, ai) in aligned)
      if (ci == null) ai!,
  ];
  final pairOfA = <int, int>{}; // agents index -> claude index
  final pairedC = <int>{};
  final candidates = <(double, int, int)>[
    for (final ci in onlyC)
      for (final ai in onlyA)
        (_similarity(c.items[ci].text, a.items[ai].text), ci, ai),
  ]..sort((x, y) => y.$1.compareTo(x.$1));
  for (final (score, ci, ai) in candidates) {
    if (score < 0.5) break;
    if (pairedC.contains(ci) || pairOfA.containsKey(ai)) continue;
    pairedC.add(ci);
    pairOfA[ai] = ci;
  }
  final entries = <_Entry>[];
  for (final (ci, ai) in aligned) {
    if (ci != null && ai != null) {
      entries.add(_Entry.common(a.items[ai]));
    } else if (ai != null) {
      final pc = pairOfA[ai];
      final at = a.items[ai].text;
      if (pc != null) {
        final ct = c.items[pc].text;
        entries.add(
          _Entry.diff(
            add(
              (id) => UnifyDiff(
                id: id,
                kind: UnifyDiffKind.changed,
                section: a.title,
                title: _itemTitle(ct),
                claudeText: ct,
                agentsText: at,
              ),
            ),
          ),
        );
      } else {
        entries.add(
          _Entry.diff(
            add(
              (id) => UnifyDiff(
                id: id,
                kind: UnifyDiffKind.onlyAgents,
                section: a.title,
                title: _itemTitle(at),
                agentsText: at,
              ),
            ),
          ),
        );
      }
    } else if (!pairedC.contains(ci)) {
      final ct = c.items[ci!].text;
      entries.add(
        _Entry.diff(
          add(
            (id) => UnifyDiff(
              id: id,
              kind: UnifyDiffKind.onlyClaude,
              section: c.title,
              title: _itemTitle(ct),
              claudeText: ct,
              claudeSpecific: _claudeSpecificRe.hasMatch(ct),
            ),
          ),
        ),
      );
    }
  }
  // The person's AGENTS.md wording of the heading wins.
  return _Block(heading: a.heading, level: a.level, entries: entries);
}

bool _isListText(String text) => _listRe.hasMatch(text);

/// The two files with [choices] (id → destination; missing = the default)
/// and [custom] texts (id → text of [UnifyTarget.custom]) (R4). The
/// `CLAUDE.md` is `@AGENTS.md` and the Claude-only part ([composeClaudeMd]).
UnifyResult composeUnify(
  UnifyPlan plan, {
  Map<String, UnifyTarget> choices = const {},
  Map<String, String> custom = const {},
}) {
  final agents = <MdSection>[];
  final claude = <MdSection>[];
  UnifyTarget target(UnifyDiff d) {
    final t = choices[d.id];
    return t != null && d.targets.contains(t) ? t : d.defaultTarget;
  }

  for (final b in plan._blocks) {
    if (b.sectionDiff case final d?) {
      (target(d) == UnifyTarget.claudeOnly ? claude : agents).add(b.section!);
      continue;
    }
    final toAgents = <MdItem>[];
    final toClaude = <MdItem>[];
    for (final e in b.entries) {
      final d = e.diff;
      if (d == null) {
        toAgents.add(e.item!);
        continue;
      }
      final side = d.claudeText ?? d.agentsText ?? '';
      switch (target(d)) {
        case UnifyTarget.agents:
          toAgents.add(MdItem(side, isList: _isListText(side)));
        case UnifyTarget.claudeOnly:
          toClaude.add(MdItem(side, isList: _isListText(side)));
        case UnifyTarget.claudeVersion:
          toAgents.add(
            MdItem(d.claudeText!, isList: _isListText(d.claudeText!)),
          );
        case UnifyTarget.agentsVersion:
          toAgents.add(
            MdItem(d.agentsText!, isList: _isListText(d.agentsText!)),
          );
        case UnifyTarget.custom:
          final text = (custom[d.id] ?? '').trim();
          if (text.isNotEmpty) {
            toAgents.add(MdItem(text, isList: _isListText(text)));
          }
      }
    }
    agents.add(MdSection(heading: b.heading, level: b.level, items: toAgents));
    if (toClaude.isNotEmpty) {
      claude.add(
        MdSection(heading: b.heading, level: b.level, items: toClaude),
      );
    }
  }
  final claudeOnly = renderMdSections(claude);
  return UnifyResult(
    agents: renderMdSections(agents),
    claude: composeClaudeMd(claudeOnly),
    claudeOnly: claudeOnly,
  );
}

