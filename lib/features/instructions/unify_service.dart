/// The user message of the AI run: the differences with their ids.
String unifyPrompt(UnifyPlan plan) {
  final b = StringBuffer()
    ..writeln('Diferenças entre o CLAUDE.md e o AGENTS.md:')
    ..writeln();
  for (final d in plan.diffs) {
    b
      ..writeln(
        '## ${d.id} · ${d.kind.name}'
        '${d.wholeSection ? ' (seção inteira)' : ''}',
      )
      ..writeln('Seção: ${d.section.isEmpty ? '(início)' : d.section}')
      ..writeln(
        'Destinos aceitos: ${[for (final t in d.targets)
          if (t != UnifyTarget.custom) t.name].join(', ')}',
      );
    if (d.claudeText case final t?) {
      b
        ..writeln('No CLAUDE.md:')
        ..writeln('```')
        ..writeln(t)
        ..writeln('```');
    }
    if (d.agentsText case final t?) {
      b
        ..writeln('No AGENTS.md:')
        ..writeln('```')
        ..writeln(t)
        ..writeln('```');
    }
    b.writeln();
  }
  return b.toString().trimRight();
}

/// The suggestions of the AI answer [data] (R4): unknown ids and
/// destinations the difference does not accept are left out.
Map<String, UnifySuggestion> parseUnifySuggestions(
  Object? data,
  UnifyPlan plan,
) {
  if (data is! Map || data['suggestions'] is! List) {
    throw const PlannerException('A IA não devolveu as sugestões.');
  }
  final out = <String, UnifySuggestion>{};
  for (final s in data['suggestions'] as List) {
    if (s is! Map) continue;
    final d = plan.diff('${s['id']}');
    if (d == null) continue;
    final target = UnifyTarget.values.asNameMap()['${s['target']}'];
    if (target == null ||
        target == UnifyTarget.custom ||
        !d.targets.contains(target)) {
      continue;
    }
    out[d.id] = UnifySuggestion(
      target: target,
      reason: '${s['reason'] ?? ''}'.trim(),
    );
  }
  return out;
}

/// Slot of the Unificar's provider line (SPEC-100 R10).
const unifySlot = 'unify-instructions';

/// Asks the AI where each difference of [plan] should go (R4).
typedef UnifySuggester = Future<Map<String, UnifySuggestion>> Function(
  UnifyPlan plan, {
  required String cwd,
});

/// "Pedir ajuda da IA" (R4): one read-only structured run on the provider
/// of "Planner e assistentes" (SPEC-100), with one suggestion per
/// difference. It only suggests: the dialog shows them, the person decides.
final unifySuggesterProvider = Provider<UnifySuggester>(
  (ref) => (plan, {required cwd}) async {
    final r = await runStructured(
      ref,
      StructuredIntent(
        cwd: cwd,
        prompt: unifyPrompt(plan),
        instructions: unifySystemPrompt,
        schema: unifySuggestionSchema,
        claude: const ClaudeStructuredExtras(maxBudgetUsd: 0.3),
        slot: unifySlot,
        label: 'o Unificar instruções',
      ),
    );
    return parseUnifySuggestions(r.data, plan);
  },
);

