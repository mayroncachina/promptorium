/// `skills/list` through a short App Server (R12): `initialize`, the extra
/// roots (when [roots] is not empty) and the list — never a thread, never a
/// turn, never a prompt to the model.
Future<CodexSkillsInventory> readCodexSkills({
  required String executable,
  required String? workspacePath,
  List<String> roots = const [],
  ProcessStarter? starter,
  String clientVersion = '0.0.0',
  bool forceReload = false,
  Duration timeout = const Duration(seconds: 15),
}) async {
  final cwd = workspacePath ?? Directory.systemTemp.path;
  final Process process;
  try {
    process = await (starter ?? _start)(
      executable,
      const ['app-server'],
      workingDirectory: cwd,
      environment: null,
    );
  } on ProcessException {
    throw const AgentUnavailable('Codex CLI não encontrado.');
  }
  final rpc = CodexRpc(process, timeout: timeout, ephemeral: true);
  final sub = rpc.messages.stream.listen((_) {});
  try {
    await rpc.request('initialize', {
      'clientInfo': {
        'name': 'promptorium',
        'title': 'Promptorium',
        'version': clientVersion,
      },
    });
    await rpc.write({'method': 'initialized', 'params': <String, dynamic>{}});
    var applied = false;
    if (roots.isNotEmpty) {
      try {
        await rpc.request('skills/extraRoots/set', {'extraRoots': roots});
        applied = true;
      } catch (_) {}
    }
    final list = await rpc.request('skills/list', {
      'cwds': [cwd],
      if (forceReload) 'forceReload': true,
    });
    return CodexSkillsInventory.parse(
      list,
      extraRoots: applied ? roots : const [],
      extraRootsApplied: applied || roots.isEmpty,
    );
  } finally {
    await sub.cancel();
    await rpc.stop(timeout: const Duration(seconds: 2));
  }
}

Future<Process> _start(
  String exe,
  List<String> args, {
  String? workingDirectory,
  Map<String, String>? environment,
}) => Process.start(exe, args, workingDirectory: workingDirectory);

/// "Atualizar" of the Skills tab: the next query passes `forceReload`.
class CodexSkillsReload extends Notifier<int> {
  @override
  int build() => 0;

  void bump() => state++;
}

final codexSkillsReloadProvider = NotifierProvider<CodexSkillsReload, int>(
  CodexSkillsReload.new,
);

/// The Codex skills of a workspace (null = global only), queried once when
/// the Skills tab opens and again with "Atualizar" (R12) — never per key.
final codexSkillsProvider = FutureProvider.autoDispose
    .family<CodexSkillsResult, String?>((ref, workspacePath) async {
      final reload = ref.watch(codexSkillsReloadProvider);
      final flows = ref.watch(providerFlowsProvider);
      if (flows.isOff('codex')) {
        return const CodexSkillsUnavailable(
          'Codex desligado nas Configurações',
        );
      }
      final starter = ref.read(codexProcessStarterProvider);
      // Like the quota reading: the App Server starts for real only with the
      // real runner, or with an injected starter (tests).
      final underTest = Platform.environment['FLUTTER_TEST'] == 'true';
      final real = identical(
        ref.read(processRunnerProvider),
        defaultProcessRunner,
      );
      if (starter == null && (!real || underTest)) {
        return const CodexSkillsUnavailable('Codex indisponível');
      }
      final caps = ref.read(codexCapabilitiesProvider);
      final home = Platform.environment['HOME'];
      final roots = caps.supports(ProviderCapability.skillsExtraRoots)
          ? codexSkillRoots(workspacePath, home: home)
          : const <String>[];
      try {
        final inv = await readCodexSkills(
          executable: ref.read(codexExecutableProvider),
          workspacePath: workspacePath,
          roots: roots,
          starter: starter,
          clientVersion: ref.read(appVersionProvider).value ?? '0.0.0',
          forceReload: reload > 0,
        );
        return CodexSkillsReady(inv);
      } on AgentUnavailable catch (e) {
        return CodexSkillsUnavailable(e.message);
      } catch (e) {
        debugPrint('codex: skills/list falhou: $e');
        return const CodexSkillsUnavailable('Codex indisponível');
      }
    });

/// Folder of the Codex's repository skills where "Disponibilizar no Codex"
/// links a Claude skill (R10, the SPEC-104 probe: `.agents/skills` and
/// `.codex/skills` are `scope: repo`).
const codexRepoSkillsDir = '.agents/skills';

/// `<root>/.agents/skills/<name>` → `../../.claude/skills/<name>`, a
/// relative symlink inside the repository (R10, P4). Never a global
/// folder; refuses when something is already there.
Future<String> linkSkillForCodex(String root, String name) async {
  final source = Directory('$root/.claude/skills/$name');
  if (!await source.exists()) {
    throw InstructionsException('A skill $name não está em .claude/skills.');
  }
  final link = Link('$root/$codexRepoSkillsDir/$name');
  if (await FileSystemEntity.type(link.path, followLinks: false) !=
      FileSystemEntityType.notFound) {
    throw InstructionsException('Já existe $codexRepoSkillsDir/$name.');
  }
  await link.parent.create(recursive: true);
  await link.create('../../.claude/skills/$name');
  return link.path;
}

/// The link of [name] in `.agents/skills`, when it points to the Claude
/// skill (R10).
String? linkedSkillDir(String root, String name) {
  final link = Link('$root/$codexRepoSkillsDir/$name');
  try {
    if (!link.existsSync()) return null;
    final target = link.resolveSymbolicLinksSync();
    final source = Directory('$root/.claude/skills/$name')
        .resolveSymbolicLinksSync();
    return target == source ? link.path : null;
  } catch (_) {
    return null;
  }
}
