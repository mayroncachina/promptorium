/// One skill of `skills/list` (R7, R8).
@immutable
class CodexSkill {
  const CodexSkill({
    required this.name,
    required this.description,
    required this.path,
    required this.scope,
    required this.enabled,
    this.pluginId,
    this.displayName,
  });

  final String name;
  final String description;

  /// Path of the `SKILL.md` as the Codex reports it.
  final String path;

  /// `user`, `repo`, `system` or `admin`.
  final String scope;
  final bool enabled;
  final String? pluginId;
  final String? displayName;

  /// Folder of the skill.
  String get dir => path.endsWith('/SKILL.md')
      ? path.substring(0, path.length - '/SKILL.md'.length)
      : path;

  /// "sistema · vem com o Codex", "plugin · image-tools" (R8).
  String get origin => pluginId != null
      ? 'plugin · $pluginId'
      : switch (scope) {
          'system' => 'sistema · vem com o Codex',
          'admin' => 'administrador',
          'repo' => 'repositório',
          _ => 'usuário · ~/.codex/skills',
        };

  static CodexSkill? fromJson(Object? j) {
    if (j is! Map || j['name'] is! String) return null;
    final ui = j['interface'];
    return CodexSkill(
      name: j['name'] as String,
      description: '${j['shortDescription'] ?? j['description'] ?? ''}',
      path: '${j['path'] ?? ''}',
      scope: '${j['scope'] ?? 'user'}',
      enabled: j['enabled'] != false,
      pluginId: j['pluginId'] as String?,
      displayName: ui is Map ? ui['displayName'] as String? : null,
    );
  }
}

/// One entry of `errors` (R9).
typedef CodexSkillError = ({String path, String message});

/// The answer of `skills/list` for one folder, plus the extra roots the
/// query handed over (R6, R7).
@immutable
class CodexSkillsInventory {
  const CodexSkillsInventory({
    required this.skills,
    required this.errors,
    required this.extraRoots,
    required this.at,
    this.extraRootsApplied = true,
  });

  final List<CodexSkill> skills;
  final List<CodexSkillError> errors;

  /// `.claude/skills` folders given by `skills/extraRoots/set`.
  final List<String> extraRoots;
  final bool extraRootsApplied;
  final DateTime at;

  factory CodexSkillsInventory.parse(
    Map<String, dynamic> response, {
    List<String> extraRoots = const [],
    bool extraRootsApplied = true,
    DateTime? at,
  }) {
    final skills = <CodexSkill>[];
    final errors = <CodexSkillError>[];
    for (final entry in response['data'] as List? ?? const []) {
      if (entry is! Map) continue;
      for (final s in entry['skills'] as List? ?? const []) {
        final skill = CodexSkill.fromJson(s);
        if (skill != null && !skills.any((k) => k.path == skill.path)) {
          skills.add(skill);
        }
      }
      for (final e in entry['errors'] as List? ?? const []) {
        if (e is Map && e['path'] is String) {
          errors.add((path: e['path'] as String, message: '${e['message']}'));
        }
      }
    }
    return CodexSkillsInventory(
      skills: skills,
      errors: errors,
      extraRoots: extraRoots,
      extraRootsApplied: extraRootsApplied,
      at: at ?? DateTime.now(),
    );
  }

  bool _under(String path, String dir) =>
      path == dir || path.startsWith(dir.endsWith('/') ? dir : '$dir/');

  /// Whether [path] lives in one of the Claude's skill folders handed over.
  bool fromExtraRoot(String path) => extraRoots.any((r) => _under(path, r));

  /// The Codex's own skills (R8): everything not served from a Claude
  /// folder (an extra root or any `.claude/skills`) — `system`, `admin`, plugins, `~/.codex/skills` and the
  /// repository ones of `.agents/skills`.
  List<CodexSkill> get own => [
    for (final s in skills)
      if (!fromExtraRoot(s.path) && !s.path.contains('/.claude/skills/')) s,
  ];

  /// What the Codex says of the Claude skill in [dir] (R7, R9, R10).
  CodexSkillStatus statusOf(String dir, {String? linkedDir}) {
    final error = errors
        .where(
          (e) =>
              _under(e.path, dir) ||
              (linkedDir != null && _under(e.path, linkedDir)),
        )
        .firstOrNull;
    if (error != null) {
      return CodexSkillStatus(CodexSkillState.error, error.message);
    }
    final skill = skills
        .where(
          (s) =>
              _under(s.path, dir) ||
              (linkedDir != null && _under(s.path, linkedDir)),
        )
        .firstOrNull;
    if (skill == null) {
      return const CodexSkillStatus(
        CodexSkillState.missing,
        'não listada pelo Codex',
      );
    }
    if (!skill.enabled) {
      return const CodexSkillStatus(
        CodexSkillState.disabled,
        'desligada no Codex',
      );
    }
    return CodexSkillStatus(
      CodexSkillState.active,
      linkedDir != null && _under(skill.path, linkedDir)
          ? 'via link em .agents/skills · ativa'
          : 'via pasta extra · ativa',
      scope: skill.scope,
    );
  }
}

enum CodexSkillState {
  active,
  disabled,
  error,
  missing,
  unavailable,
  claudeOnly,
}

/// The Codex badge and panel line of one Claude skill (R7).
@immutable
class CodexSkillStatus {
  const CodexSkillStatus(this.state, this.detail, {this.scope});

  final CodexSkillState state;

  /// "via pasta extra · ativa", "desligada no Codex", the `skills/list`
  /// error, "Codex indisponível".
  final String detail;
  final String? scope;

  bool get visible => state == CodexSkillState.active;

  /// Text of the badge in the list.
  String get badge => switch (state) {
    CodexSkillState.active => 'Codex',
    CodexSkillState.error => 'Codex · erro',
    CodexSkillState.disabled => 'Codex · desligada',
    CodexSkillState.claudeOnly => 'Só Claude Code',
    CodexSkillState.missing || CodexSkillState.unavailable => 'Codex · —',
  };
}

