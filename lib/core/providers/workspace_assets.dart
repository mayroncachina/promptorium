/// Hash of a `CLAUDE.md` (sha256 of its UTF-8 bytes), kept in the marker of
/// the generated `AGENTS.md` (R3).
String claudeMdHash(String claude) =>
    sha256.convert(utf8.encode(claude)).toString();

final _marker = RegExp(r'promptorium:origem sha256=([0-9a-f]{64})');

/// The header of a generated `AGENTS.md` (R3, P2: full copy).
String agentsMdHeader(String hash) =>
    '<!-- Gerado do CLAUDE.md pelo Promptorium. Edite o CLAUDE.md.\n'
    '     promptorium:origem sha256=$hash -->\n';

/// The `AGENTS.md` generated from [claude]: header + full copy (P2).
String generatedAgentsMd(String claude) =>
    '${agentsMdHeader(claudeMdHash(claude))}$claude';

/// The source hash in the marker of [agents]; null = not generated by the
/// app (a file of the person's, R4).
String? agentsMdMarker(String agents) {
  final head = agents.length > 400 ? agents.substring(0, 400) : agents;
  return _marker.firstMatch(head)?.group(1);
}

/// [agents] without the generated header (the copy of the CLAUDE.md it
/// was made from).
String agentsMdBody(String agents) {
  final end = agents.indexOf('-->\n');
  if (agentsMdMarker(agents) == null || end < 0) return agents;
  return agents.substring(end + 4);
}

/// The `AGENTS.md` of a folder against its `CLAUDE.md` (R4).
enum AgentsMdState {
  /// No `AGENTS.md`.
  absent,

  /// Generated by the app and equal to the `CLAUDE.md`.
  fresh,

  /// Generated by the app; the `CLAUDE.md` changed since.
  stale,

  /// Written by the person (no marker): never overwritten.
  personal,
}

AgentsMdState agentsMdState({String? claude, String? agents}) {
  if (agents == null) return AgentsMdState.absent;
  final hash = agentsMdMarker(agents);
  if (hash == null) return AgentsMdState.personal;
  return claude != null && claudeMdHash(claude) == hash
      ? AgentsMdState.fresh
      : AgentsMdState.stale;
}

class InstructionsException implements Exception {
  const InstructionsException(this.message);

  final String message;

  @override
  String toString() => message;
}

/// Writes `<root>/AGENTS.md` generated from `<root>/CLAUDE.md` (R3, R4).
/// Refuses a file of the person's (no marker) — always — and replaces a
/// generated one only with [replaceGenerated] (after the diff was shown).
Future<String> writeGeneratedAgentsMd(
  String root, {
  bool replaceGenerated = false,
}) async {
  final claude = File('$root/$claudeMdName');
  if (!await claude.exists()) {
    throw const InstructionsException('O projeto não tem CLAUDE.md.');
  }
  final text = await claude.readAsString();
  final target = File('$root/$agentsMdName');
  if (await target.exists()) {
    final current = await target.readAsString();
    if (agentsMdMarker(current) == null) {
      throw const InstructionsException(
        'O AGENTS.md foi escrito por você: o app não o sobrescreve.',
      );
    }
    if (!replaceGenerated) {
      throw const InstructionsException(
        'O AGENTS.md gerado já existe: confira a diferença antes de atualizar.',
      );
    }
  }
  final out = generatedAgentsMd(text);
  final tmp = File('${target.path}.promptorium-tmp');
  await tmp.writeAsString(out, flush: true);
  await tmp.rename(target.path);
  return out;
}

/// One instruction file of the project (R5): only metadata, read on demand.
@immutable
class InstructionFile {
  const InstructionFile({
    required this.path,
    required this.size,
    required this.modified,
    required this.lines,
  });

  /// Relative to the project root (`CLAUDE.md`, `packages/api/AGENTS.md`).
  final String path;
  final int size;
  final DateTime modified;
  final int lines;

  String get name => path.split('/').last;
  bool get nested => path.contains('/');
}

/// The instruction files of a project (R5).
@immutable
class InstructionsInventory {
  const InstructionsInventory({
    required this.root,
    this.claude,
    this.agents,
    this.claudeText,
    this.agentsText,
    this.nested = const [],
  });

  final String root;
  final InstructionFile? claude;
  final InstructionFile? agents;
  final String? claudeText;
  final String? agentsText;

  /// `CLAUDE.md` / `AGENTS.md` of subfolders: read-only (P3).
  final List<InstructionFile> nested;

  AgentsMdState get agentsState =>
      agentsMdState(claude: claudeText, agents: agentsText);
}

/// Folders never searched for nested instruction files.
const _skipDirs = {'node_modules', 'build', 'dist', 'target', 'vendor', 'Pods'};

Future<InstructionFile> _fileInfo(String root, File f) async {
  final stat = await f.stat();
  var lines = 0;
  try {
    lines = '\n'.allMatches(await f.readAsString()).length;
  } catch (_) {}
  return InstructionFile(
    path: f.path.substring(root.length + 1),
    size: stat.size,
    modified: stat.modified,
    lines: lines,
  );
}

/// Reads the root files and searches subfolders (up to [depth] levels,
/// skipping dot folders and build output) for nested ones.
Future<InstructionsInventory> scanInstructions(
  String root, {
  int depth = 4,
}) async {
  Future<(InstructionFile, String)?> top(String name) async {
    final f = File('$root/$name');
    if (!await f.exists()) return null;
    return (await _fileInfo(root, f), await f.readAsString());
  }

  final claude = await top(claudeMdName);
  final agents = await top(agentsMdName);
  final nested = <InstructionFile>[];
  Future<void> walk(Directory d, int level) async {
    if (level > depth || nested.length >= 50) return;
    List<FileSystemEntity> children;
    try {
      children = await d.list(followLinks: false).toList();
    } catch (_) {
      return;
    }
    children.sort((a, b) => a.path.compareTo(b.path));
    for (final e in children) {
      final name = e.path.split('/').last;
      if (e is Directory) {
        if (name.startsWith('.') || _skipDirs.contains(name)) continue;
        await walk(e, level + 1);
      } else if (e is File &&
          level > 0 &&
          (name == claudeMdName || name == agentsMdName)) {
        nested.add(await _fileInfo(root, e));
      }
    }
  }

  await walk(Directory(root), 0);
  return InstructionsInventory(
    root: root,
    claude: claude?.$1,
    claudeText: claude?.$2,
    agents: agents?.$1,
    agentsText: agents?.$2,
    nested: nested,
  );
}

final instructionsInventoryProvider = FutureProvider.autoDispose
    .family<InstructionsInventory, String>(
      (ref, root) => scanInstructions(root),
    );

/// The proof of one Codex run (R2): the `instructionSources` of its
/// `promptorium_run` event, the moment and where it ran.
@immutable
class InstructionsProof {
  const InstructionsProof({
    required this.sources,
    required this.at,
    required this.where,
  });

  /// Relative to the run's folder (`CLAUDE.md`), or absolute.
  final List<String> sources;
  final DateTime at;

  /// `sessão “Corrigir cache”`, `conversa “…”`.
  final String where;

  /// Whether the run loaded [name] of the project root.
  bool loaded(String name) => sources.contains(name);
}

/// The last Codex run of the workspace that reported `instructionSources`
/// (sessions and conversations of the Prompt). Null = none yet: the screen
/// says "previsto", never "carregado" (R2).
final instructionsProofProvider = FutureProvider.autoDispose
    .family<InstructionsProof?, int>((ref, workspaceId) async {
      final db = ref.watch(appDatabaseProvider);
      const needle = '%"instructionSources"%';
      final rows = await db
          .customSelect(
            'SELECT e.json AS json, e.created_at AS at, s.title AS title, '
            "'sessão' AS kind FROM session_events e "
            'JOIN sessions s ON s.id = e.session_id '
            'WHERE s.workspace_id = ? AND e.type = ? AND e.json LIKE ? '
            'UNION ALL '
            'SELECT e.json AS json, e.created_at AS at, c.title AS title, '
            "'conversa' AS kind FROM conversation_events e "
            'JOIN conversations c ON c.id = e.conversation_id '
            'WHERE c.workspace_id = ? AND e.type = ? AND e.json LIKE ? '
            'ORDER BY at DESC LIMIT 5',
            variables: [
              Variable.withInt(workspaceId),
              Variable.withString('promptorium_run'),
              Variable.withString(needle),
              Variable.withInt(workspaceId),
              Variable.withString('promptorium_run'),
              Variable.withString(needle),
            ],
            readsFrom: {
              db.sessionEvents,
              db.sessions,
              db.conversationEvents,
              db.conversations,
            },
          )
          .get();
      for (final r in rows) {
        try {
          final j = jsonDecode(r.data['json'] as String);
          if (j is! Map || j['provider'] != 'codex') continue;
          final sources = j['instructionSources'];
          if (sources is! List) continue;
          final at =
              DateTime.tryParse('${j['at']}') ??
              DateTime.fromMillisecondsSinceEpoch(
                ((r.data['at'] as int?) ?? 0) * 1000,
              );
          final title = '${r.data['title'] ?? ''}'.trim();
          final kind = r.data['kind'] as String;
          return InstructionsProof(
            sources: [for (final s in sources) '$s'],
            at: at,
            where: title.isEmpty ? kind : '$kind “$title”',
          );
        } catch (_) {
          continue;
        }
      }
      return null;
    });

